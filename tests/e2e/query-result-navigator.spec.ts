import { realpathSync } from 'node:fs';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { confirmOwnedDesktopExit, dataDir, desktop, expect, page, pageErrors, retainOwnedDesktopResources, test } from './desktop-fixture';
import { queryResultNavigatorZh as text } from '../../src/renderer/locales/queryResultNavigator.zh-CN';
import { queryResultColumnsZh as columnsText } from '../../src/renderer/locales/queryResultColumns.zh-CN';
import { queryResultFilterZh as filterText } from '../../src/renderer/locales/queryResultFilter.zh-CN';
import { queryResultSortZh as sortText } from '../../src/renderer/locales/queryResultSort.zh-CN';
import { queryResultKeywordZh as keywordText } from '../../src/renderer/locales/queryResultKeyword.zh-CN';
import { queryResultFindZh as findText } from '../../src/renderer/locales/queryResultFind.zh-CN';
import { gridRowHeightZh as heightText } from '../../src/renderer/locales/gridRowHeight.zh-CN';
import { queryPinsZh as pinText } from '../../src/renderer/locales/queryPins.zh-CN';
import { queryDuplicateZh as duplicateText } from '../../src/renderer/locales/queryDuplicate.zh-CN';
import { historyPagesZh as previewText } from '../../src/renderer/locales/historyPages.zh-CN';
import { navigationMenuItem } from './navigation-menu';
import { zh } from '../../src/renderer/locales/zh-CN';

test.use({ trace: 'off', screenshot: 'off', video: 'off', preserveOnUnconfirmedExit: true });
test.skip(process.env.DBARK_QUERY_RESULT_NAVIGATOR_TEST !== '1', '仅在隔离的 SQLite 源码验收运行');

test('多结果查询按名称、字段、SQL预览及序号切换，保持原执行和编辑器正文', async ({}, info) => {
  if (process.env.DBARK_INTEGRATION_ENABLED !== '0' || process.env.DBARK_DEV_URL || process.env.DBARK_EXECUTABLE_PATH)
    throw Error('结果集导航验收只使用本例临时 SQLite 文件');
  try {
    const database = join(realpathSync(dataDir), 'result-navigator.sqlite');
    const fixture = new DatabaseSync(database);
    fixture.exec('CREATE TABLE fixture (id INTEGER PRIMARY KEY)');
    fixture.close();
    const sql = Array.from({ length: 44 }, (_, index) => {
      const number = index + 1;
      const title = number === 2 || number === 42 ? '-- NAME: 月度汇总\n' : '';
      const column = number === 44 ? 'UniqueOutput' : 'sample';
      const comment = number === 44 ? ` /* ${'x'.repeat(66000)}完整原语句尾部🚢 */` : number === 41 ? ' /* navigator_receipt_🧭 */' : '';
      const additional = number === 11 || number === 12 ? ', 100 AS layout_note, 200 AS layout_flag' : '';
      const moreRows = number === 11 ? [17, 13, 15] : number === 12 ? [18, 16, 14] : [];
      const union = moreRows.map(value => ` UNION ALL SELECT ${value}, 100, 200`).join('');
      return `${title}SELECT ${number} AS ${column}${additional}${union}${comment};`;
    }).join('\n');
    // 只替换文件选择器。连接、执行、缓存及结果切换仍使用正式应用。
    await desktop.evaluate(({ dialog }, file) => {
      const original = dialog.showOpenDialog;
      dialog.showOpenDialog = (async (...args: unknown[]) => {
        dialog.showOpenDialog = original;
        if (!(args.at(-1) as Electron.OpenDialogOptions).filters?.[0]?.extensions.includes('sqlite'))
          throw Error('本例仅允许选择指定 SQLite 文件');
        return { canceled: false, filePaths: [file] };
      }) as typeof original;
    }, database);
    await page.evaluate(async sql => {
      const id = 'result-navigator';
      const file = await window.dbark.invoke('files.choose', { purpose: 'sqlite-database', sqliteConnectionId: id });
      if (!file) throw Error('SQLite 文件选择未完成');
      await window.dbark.invoke('connections.save', { id, name: '结果导航样本', dialect: 'sqlite', group: '', color: '#51bda5',
        sqlite: { fileToken: file.token, readOnly: true, busyTimeoutMs: 1000 } });
      const settings = await window.dbark.invoke('settings.get', {});
      await window.dbark.invoke('settings.save', { ...settings, activeTabId: id, tabs: [
        { id, kind: 'query', title: '多结果查询', connectionId: id, database: 'main', sql },
      ] });
    }, sql);
    await page.reload();
    const tab = page.locator('.query-tab:visible'), trigger = tab.getByRole('button', { name: text.open, exact: true });
    await tab.locator('.query-execute-split').getByRole('button', { name: new RegExp(zh.query.text010) }).first().click();
    await expect(trigger).toBeEnabled();
    const history = () => page.evaluate(() => window.dbark.invoke('history.list', {}));
    const tasks = () => page.evaluate(() => window.dbark.invoke('tasks.list', {}));
    const originalHistory = await history(), originalTasks = await tasks();
    expect(originalHistory).toHaveLength(1);
    const dialog = page.getByRole('dialog', { name: text.open, exact: true });
    const search = dialog.getByRole('combobox', { name: text.input, exact: true });
    const grid = tab.getByRole('grid');
    const columns = page.getByRole('dialog', {name: columnsText.title, exact: true});
    const openColumns = async () => (await navigationMenuItem(tab, {name: columnsText.open, exact: true})).click();
    const applyColumns = async () => {
      await columns.getByRole('button', {name: columnsText.apply, exact: true}).click();
      await expect(columns).toBeHidden();
    };
    const filter = tab.getByRole('region', {name: filterText.title, exact: true});
    const openFilter = async () => (await navigationMenuItem(tab, {name: filterText.open, exact: true})).click();
    const applyFilter = async (upper: number) => {
      await openFilter();
      await filter.getByRole('button', {name: filterText.add, exact: true}).click();
      await filter.getByLabel(`${filterText.column} 1`, {exact: true}).selectOption('c0');
      await filter.getByLabel(filterText.sqliteType(1), {exact: true}).selectOption('integer');
      await filter.getByLabel(`${filterText.operator} 1`, {exact: true}).selectOption('lt');
      await filter.getByLabel(`${filterText.input} 1`, {exact: true}).fill(String(upper));
      await filter.getByRole('button', {name: filterText.apply, exact: true}).click();
      await expect(filter).toBeHidden();
    };
    const applySort = async (direction: 'ASC' | 'DESC') => {
      await (await navigationMenuItem(tab, {name: sortText.panelTitle, exact: true})).click();
      const sort = tab.getByRole('region', {name: sortText.panelTitle, exact: true});
      await sort.getByRole('button', {name: sortText.panelAdd, exact: true}).click();
      await sort.getByLabel(sortText.panelField(1), {exact: true}).selectOption('c0');
      await sort.getByLabel(sortText.panelDirection(1), {exact: true}).selectOption(direction);
      await sort.getByRole('button', {name: sortText.panelApply, exact: true}).click();
      await expect(sort).toBeHidden();
    };
    const sampleValues = () => grid.getByRole('gridcell').filter({hasText: /^(11|12|13|14|15|16|17|18)$/});
    const resultBody = tab.locator('.query-layout-results > .result-body');
    await grid.getByRole('gridcell', {name: '1', exact: true}).focus();
    await page.keyboard.press('ControlOrMeta+Shift+PageUp');
    await expect(grid.getByRole('gridcell', {name: '44', exact: true})).toBeVisible();
    await expect(resultBody).toBeFocused();
    await page.keyboard.press('ControlOrMeta+Shift+PageDown');
    await expect(grid.getByRole('gridcell', {name: '1', exact: true})).toBeVisible();
    await trigger.click(); await search.fill('#11'); await search.press('Enter');
    await expect(grid.getByRole('gridcell', {name: '11', exact: true})).toBeVisible();
    await openColumns();
    await columns.getByLabel(columnsText.visible(2), {exact: true}).uncheck();
    await columns.getByRole('button', {name: columnsText.up(3), exact: true}).click();
    await columns.getByRole('button', {name: columnsText.up(3), exact: true}).click();
    await columns.getByRole('button', {name: columnsText.freezeThrough(3), exact: true}).click();
    await columns.getByLabel(columnsText.width(3), {exact: true}).fill('240');
    await columns.getByLabel(heightText.label, {exact: true}).selectOption('56');
    await applyColumns();
    await applyFilter(17); await applySort('DESC');
    await expect(sampleValues()).toHaveText(['15', '13', '11']);
    await page.keyboard.press('ControlOrMeta+Shift+PageDown');
    await expect(grid.getByRole('gridcell', {name: '12', exact: true})).toBeVisible();
    const note = grid.getByRole('columnheader', {name: /^layout_note/});
    const flag = grid.getByRole('columnheader', {name: /^layout_flag/});
    await expect(note).toBeVisible();
    await openColumns();
    await columns.getByLabel(columnsText.width(2), {exact: true}).fill('190');
    await columns.getByLabel(heightText.label, {exact: true}).selectOption('24');
    await applyColumns();
    await applyFilter(18); await applySort('ASC');
    await page.keyboard.press('ControlOrMeta+Shift+PageUp');
    await expect(grid.getByRole('gridcell', {name: '11', exact: true})).toBeVisible();
    await expect(sampleValues()).toHaveText(['15', '13', '11']);
    await expect(note).toHaveCount(0);
    await expect(grid).toHaveClass(/grid-row-height-56/);
    await expect(grid.getByRole('columnheader').filter({hasText: /sample|layout_flag/}).first()).toContainText('layout_flag');
    await expect(flag).toHaveCSS('width', '240px');
    await expect(flag).toHaveClass(/rdg-cell-frozen-start/);
    await page.keyboard.press('ControlOrMeta+Shift+PageDown');
    await expect(grid.getByRole('gridcell', {name: '12', exact: true})).toBeVisible();
    await expect(sampleValues()).toHaveText(['12', '14', '16']);
    await expect(note).toHaveCSS('width', '190px');
    await expect(grid).toHaveClass(/grid-row-height-24/);
    await tab.locator('.monaco-editor').getByRole('textbox').focus();
    await page.keyboard.press('ControlOrMeta+Shift+F8');
    await expect(search).toBeFocused();
    await expect(dialog.getByRole('option')).toHaveCount(40);
    await expect(dialog.getByText(text.receiptHint, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: text.next, exact: true }).click();
    await expect(dialog.getByRole('option')).toHaveCount(4);
    await search.fill('NAVIGATOR_RECEIPT_🧭');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await expect(dialog.getByRole('option')).toContainText('结果 41');
    await expect(dialog.locator('.query-result-navigator-sql')).toContainText('SELECT 41 AS sample');
    await dialog.screenshot({ path: info.outputPath('按SQL预览查找结果.png') });
    await search.press('Enter');
    await expect(grid.getByRole('gridcell', { name: '41', exact: true })).toBeVisible();
    await trigger.click();
    // 回执之后的尾部只属于完整原语句，不能把目录查找声称为原文全文搜索。
    await search.fill('完整原语句尾部🚢');
    await expect(dialog.getByRole('option')).toHaveCount(0);
    await search.fill('@42');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await expect(dialog.getByRole('option')).toContainText(text.statement(42));
    await search.fill('月度汇总');
    await expect(dialog.getByRole('option')).toHaveCount(2);
    await search.press('ArrowDown');
    await expect(dialog.getByRole('option', { selected: true })).toContainText('结果 42');
    await dialog.screenshot({ path: info.outputPath('查找结果集.png') });
    await search.press('Enter');
    await expect(dialog).toHaveCount(0);
    await expect(grid.getByRole('gridcell', { name: '42', exact: true })).toBeVisible();

    await trigger.click();
    await search.fill('uniqueoutput');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await dialog.getByRole('option').click();
    await expect(grid.getByRole('gridcell', { name: '44', exact: true })).toBeVisible();
    await (await navigationMenuItem(tab, { name: zh.query.resultSql, exact: true })).click();
    const sourceDialog = page.getByRole('dialog', { name: zh.query.resultSqlTitle, exact: true });
    await expect(sourceDialog.locator('.monaco-editor .view-lines')).not.toContainText('完整原语句尾部');
    await sourceDialog.getByRole('button', { name: zh.query.resultSqlShowFull, exact: true }).click();
    const full = sourceDialog.getByRole('region', { name: zh.query.resultSqlFullTitle, exact: true });
    const find = full.getByRole('textbox', { name: previewText.sqlFindTitle, exact: true });
    await find.fill('完整原语句尾部🚢');
    await find.press('Enter');
    await expect(full.locator('mark')).toHaveText('完整原语句尾部🚢');
    await expect(full.getByRole('status', { name: previewText.sqlPartStatus, exact: true })).toHaveText('第 2 / 2 段');
    await sourceDialog.screenshot({ path: info.outputPath('完整结果原语句.png') });
    await sourceDialog.getByRole('button', { name: zh.common.close, exact: true }).click();
    expect(await history()).toEqual(originalHistory);
    expect(await tasks()).toEqual(originalTasks);
    await trigger.click();
    await search.fill('#2');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await search.press('Escape');
    await expect(trigger).toBeFocused();
    await expect(grid.getByRole('gridcell', { name: '44', exact: true })).toBeVisible();
    await trigger.click();
    await search.fill('不存在的列');
    await expect(dialog.getByText(text.empty, { exact: true })).toBeVisible();
    await search.press('Enter');
    await expect(dialog).toBeVisible();
    await search.fill('#2');
    await search.press('Enter');
    await expect(grid.getByRole('gridcell', { name: '2', exact: true })).toBeVisible();
    expect(await history()).toEqual(originalHistory);
    expect(await tasks()).toEqual(originalTasks);
    const settings = () => page.evaluate(() => window.dbark.invoke('settings.get', {}));
    expect((await settings()).tabs.map(tab => tab.sql)).toEqual([sql]);

    const openStatement = tab.getByRole('button', { name: duplicateText.resultStatement, exact: true });
    const target = page.getByRole('dialog', { name: duplicateText.targetAction, exact: true });
    await openStatement.click();
    await expect(target.getByRole('button', { name: duplicateText.targetOpen, exact: true })).toBeDisabled();
    await target.getByRole('button', { name: zh.common.cancel, exact: true }).click();
    expect((await settings()).tabs).toHaveLength(1);
    await expect(grid.getByRole('gridcell', { name: '2', exact: true })).toBeVisible();
    await openStatement.click();
    await target.getByLabel(duplicateText.targetConnection, { exact: true }).selectOption('result-navigator');
    await expect(target.getByLabel(duplicateText.targetDatabase, { exact: true })).toHaveValue('main');
    await target.screenshot({ path: info.outputPath('结果语句选择目标.png') });
    await target.getByRole('button', { name: duplicateText.targetOpen, exact: true }).click();
    await expect(target).toHaveCount(0);
    await expect.poll(async () => (await settings()).tabs.map(tab => tab.sql)).toEqual([sql, 'SELECT 2 AS sample;']);
    await expect(tab.getByRole('grid')).toHaveCount(0);
    await page.locator('.tab-strip').getByRole('button', { name: '多结果查询', exact: true }).click();
    await expect(grid.getByRole('gridcell', { name: '2', exact: true })).toBeVisible();
    await expect(openStatement).toBeEnabled();
    await tab.locator('.monaco-editor').getByRole('textbox').focus();
    await page.keyboard.insertText(' ');
    await expect(openStatement).toBeDisabled();
    await (await navigationMenuItem(tab, { name: zh.query.resultSql, exact: true })).click();
    await expect(sourceDialog.getByRole('button', { name: zh.query.resultSqlShowFull, exact: true })).toHaveCount(0);
    await sourceDialog.getByRole('button', { name: zh.common.close, exact: true }).click();
    expect(await history()).toEqual(originalHistory);
    expect(await tasks()).toEqual(originalTasks);

    const pinGroup = tab.getByRole('group', { name: zh.query.pinSection, exact: true });
    const pinCurrent = async () => (await navigationMenuItem(tab, { name: zh.query.pinResult, exact: true })).click();
    await pinCurrent();
    await expect(pinGroup.getByRole('button', { name: '固定 1 · 月度汇总', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await openColumns();
    await columns.getByLabel(columnsText.width(1), {exact: true}).fill('208');
    await applyColumns();
    await applyFilter(3);
    const keyword = tab.getByRole('searchbox', { name: keywordText.input, exact: true });
    await keyword.fill('2');
    await keyword.press('Enter');
    await expect(tab.getByRole('search', { name: keywordText.input, exact: true }).getByRole('status'))
      .toHaveText(keywordText.counts(1, 1));
    const openFind = () => tab.getByRole('button', { name: findText.open, exact: true }).click();
    const findInput = tab.getByRole('textbox', { name: findText.input, exact: true });
    const findStatus = tab.locator('.query-result-find-status').getByRole('status');
    await openFind();
    await findInput.fill('2');
    await expect(findStatus).toHaveText(findText.count(1, -1));
    await trigger.click();
    await search.fill('#44');
    await search.press('Enter');
    await expect(grid.getByRole('gridcell', { name: '44', exact: true })).toBeVisible();
    await pinCurrent();
    await expect(pinGroup.getByRole('button', { name: '固定 2', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const editor = tab.locator('.monaco-editor').getByRole('textbox');
    await editor.focus();
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+a' : 'Control+a');
    const latestSql = "SELECT '后续执行值' AS latest_only;";
    await page.keyboard.insertText(latestSql);
    await tab.locator('.query-execute-split').getByRole('button', { name: new RegExp(zh.query.text010) }).first().click();
    await expect(grid.getByRole('gridcell', { name: '后续执行值', exact: true })).toBeVisible();
    await expect.poll(async () => (await history()).length).toBe(originalHistory.length + 1);
    const nextHistory = await history(), nextTasks = await tasks();
    await trigger.click();
    await search.fill('月度汇总');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await expect(dialog.getByRole('option')).toContainText('固定 1 · 月度汇总');
    await dialog.getByRole('button', { name: text.sources.current, exact: true }).click();
    await expect(dialog.getByRole('option')).toHaveCount(0);
    await dialog.getByRole('button', { name: text.sources.pinned, exact: true }).click();
    await expect(search).toBeFocused();
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await dialog.screenshot({ path: info.outputPath('按名称查找固定结果.png') });
    await search.press('Enter');
    await expect(grid.getByRole('gridcell', { name: '2', exact: true })).toBeVisible();
    const rowCheck = grid.getByRole('row').filter({ hasText: /^2$/ }).getByRole('checkbox');
    await rowCheck.check();
    await expect(rowCheck).toBeChecked();
    const rename = tab.getByRole('button', { name: pinText.rename, exact: true });
    const renameDialog = page.getByRole('dialog', { name: pinText.rename, exact: true });
    const pinName = renameDialog.getByRole('textbox', { name: pinText.name, exact: true });
    const saveName = renameDialog.getByRole('button', { name: zh.common.save, exact: true });
    await rename.click();
    await expect(pinName).toHaveValue('固定 1 · 月度汇总');
    await pinName.fill('中'.repeat(86));
    await expect(saveName).toBeDisabled();
    await pinName.press('Escape');
    await expect(rename).toBeFocused();
    await expect(rowCheck).toBeChecked();
    await rename.click();
    await pinName.fill('上月对账基准📌');
    await renameDialog.screenshot({ path: info.outputPath('重命名固定结果.png') });
    await saveName.click();
    const renamedPin = pinGroup.getByRole('button', { name: '上月对账基准📌', exact: true });
    await expect(renamedPin).toHaveAttribute('aria-pressed', 'true');
    await expect(renamedPin).toHaveAttribute('title', /执行耗时 .* ms\nSELECT 2 AS sample/);
    await expect(rowCheck).toBeChecked();
    await page.keyboard.press('ControlOrMeta+Shift+PageUp');
    await expect(grid.getByRole('gridcell', {name: '后续执行值', exact: true})).toBeVisible();
    await expect(renamedPin).toHaveAttribute('aria-pressed', 'false');
    await renamedPin.click();
    await expect(grid.getByRole('gridcell', {name: '2', exact: true})).toBeVisible();
    await expect(keyword).toHaveValue('2');
    await expect(grid.getByRole('columnheader', {name: /^sample/})).toHaveCSS('width', '208px');
    await openFind();
    await expect(findInput).toHaveValue('2');
    await expect(findStatus).toHaveText(findText.count(1, -1));
    await tab.getByRole('button', { name: findText.close, exact: true }).click();
    await openFilter();
    await expect(filter.getByLabel(`${filterText.input} 1`, {exact: true})).toHaveValue('3');
    await filter.getByRole('button', {name: filterText.cancel, exact: true}).click();
    await trigger.click();
    await expect(dialog.getByRole('option', { selected: true })).toContainText('上月对账基准📌');
    await search.fill('月度汇总');
    await expect(dialog.getByRole('option')).toContainText('上月对账基准📌');
    await search.fill('上月对账基准');
    await expect(dialog.getByRole('option')).toContainText('上月对账基准📌');
    await dialog.screenshot({ path: info.outputPath('按新名称查找固定结果.png') });
    // 旧快照来自前次第 2 条语句，当前执行只有第 1 条。
    await search.fill('@2');
    await expect(dialog.getByRole('option')).toHaveCount(0);
    await search.fill('uniqueoutput');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await dialog.getByRole('option').click();
    await expect(grid.getByRole('gridcell', { name: '44', exact: true })).toBeVisible();
    await trigger.click();
    await search.fill('#1');
    await expect(dialog.getByRole('option')).toHaveCount(1);
    await expect(dialog.getByRole('option')).toContainText('结果 1');
    await search.press('Enter');
    await expect(grid.getByRole('gridcell', { name: '后续执行值', exact: true })).toBeVisible();
    await expect(pinGroup.getByRole('button', { name: zh.query.currentResults, exact: true })).toHaveAttribute('aria-pressed', 'true');
    expect((await settings()).tabs[0].sql).toBe(latestSql);
    expect(await history()).toEqual(nextHistory);
    expect(await tasks()).toEqual(nextTasks);
    expect(pageErrors).toEqual([]);
    await confirmOwnedDesktopExit(info);
  } catch (reason) {
    retainOwnedDesktopResources(info);
    throw reason;
  }
});
