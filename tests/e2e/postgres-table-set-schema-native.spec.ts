test.use({ trace: 'off', screenshot: 'off', video: 'off' });
test.skip(process.env.DBARK_POSTGRES_WORKSPACE_NATIVE !== '1', '需要本轮隔离 PostgreSQL');
test.setTimeout(60_000);

function fixture() {
  const user = process.env.DBARK_POSTGRES_TEST_USER ?? '', database = process.env.DBARK_POSTGRES_TEST_DATABASE ?? '';
  const password = process.env.DBARK_POSTGRES_TEST_PASSWORD ?? '', port = Number(process.env.DBARK_POSTGRES_TEST_PORT);
  if (process.env.DBARK_INTEGRATION_ENABLED !== '1' || !/^tabrelio_pg_[a-f0-9]{12}$/.test(user) || database !== user ||
      !/^[a-f0-9]{64}$/.test(password) || !Number.isInteger(port) || port <= 1024 || port > 65535) throw Error('需要本轮独占回环库');
  return { host: '127.0.0.1', port, user, database, password, connectionTimeoutMillis: 3000 };
}

async function saveConnection(config: ReturnType<typeof fixture>) {
  return page.evaluate(async ({ host, port, user, database, password }) => (await window.dbark.invoke('connections.save', {
    id: '', name: 'PostgreSQL 移表测试', group: '', color: '#123456', dialect: 'postgresql',
    host, port, user, database, password, rememberPassword: false,
  })).id, config);
}

test('PostgreSQL 跨 schema 移表保留对象身份、数据、序列和收藏', async ({}, info) => {
  const config = fixture(), observer = new Client(config);
  const sourceSchema = '移表来源', targetSchema = '归档 "区"', name = postgresIdentifier('订单 "A"');
  const source = postgresIdentifier(sourceSchema), target = postgresIdentifier(targetSchema);
  const original = source + '.' + name, moved = target + '.' + name;
  await observer.connect();
  try {
    await observer.query(`CREATE SCHEMA ${source}; CREATE SCHEMA ${target};
      CREATE TABLE ${original} (
        id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME ${source}.move_order_id START WITH 7),
        note text NOT NULL, CONSTRAINT move_order_pk PRIMARY KEY(id), CONSTRAINT move_order_positive CHECK(id>0)
      );
      CREATE INDEX move_order_note_idx ON ${original}(note);
      CREATE SEQUENCE ${source}.unowned_move_seq;
      CREATE VIEW ${source}.move_order_view AS SELECT id,note FROM ${original};
      INSERT INTO ${original}(note) VALUES ('跨 schema 保留的记录');
      CREATE TABLE ${source}.move_order_ref(id bigint REFERENCES ${original}(id));
      INSERT INTO ${source}.move_order_ref VALUES (7);
      CREATE TABLE ${target}.move_order_note_idx(id integer)`);
    const oid = async (qualified: string) => (await observer.query('SELECT to_regclass($1)::oid::text AS oid', [qualified])).rows[0].oid;
    const originalOid = await oid(original), sequenceOid = await oid(source + '.move_order_id'), indexOid = await oid(source + '.move_order_note_idx');
    const unownedOid = await oid(source + '.unowned_move_seq');
    const constraints = async () => (await observer.query(`SELECT oid::text,conname::text FROM pg_catalog.pg_constraint
      WHERE conrelid=$1::oid ORDER BY oid`, [originalOid])).rows;
    const beforeConstraints = await constraints();
    const connectionId = await saveConnection(config);
    await page.evaluate(async ({ connectionId, database, original }) => {
      const workbench = await window.dbark.invoke('workbench.get', {});
      await window.dbark.invoke('workbench.save', { ...workbench, document: { ...workbench.document, favorites: [
        { id: 'pg-move-favorite', label: '移动时保留的自定义名称', groupId: null, target: { kind: 'table', connectionId, database, name: original } },
      ] } });
      const settings = await window.dbark.invoke('settings.get', {});
      await window.dbark.invoke('settings.save', { ...settings, activeTabId: 'pg-move-source', tabs: [
        { id: 'pg-move-source', title: '原表记录', kind: 'table', connectionId, database, table: original },
      ] });
    }, { connectionId, database: config.database, original });
    await page.reload();

    const gridTab = page.locator('.postgres-table-tab:visible'), dialog = page.getByRole('dialog', { name: structure.title, exact: true });
    const panel = dialog.getByRole('region', { name: manage.title, exact: true });
    const button = (name: string) => panel.getByRole('button', { name, exact: true });
    const chooser = panel.getByRole('combobox', { name: manage.schema, exact: true });
    const open = async (schema: string, current: string) => {
      await gridTab.getByRole('button', { name: structure.open, exact: true }).click();
      await dialog.getByRole('button', { name: manage.title, exact: true }).click();
      await panel.getByRole('combobox', { name: manage.operation, exact: true }).selectOption('move');
      await expect(chooser.getByRole('option', { name: schema, exact: true })).toHaveCount(1);
      await expect(chooser.getByRole('option', { name: current, exact: true })).toHaveCount(0);
      await chooser.selectOption(schema);
    };
    const favorite = (qualified: string) => expect.poll(() => page.evaluate(async () =>
      (await window.dbark.invoke('workbench.get', {})).document.favorites)).toMatchObject([
      { id: 'pg-move-favorite', label: '移动时保留的自定义名称', target: { kind: 'table', name: qualified } },
    ]);
    await expect(gridTab.getByRole('grid')).toContainText('跨 schema 保留的记录');
    await open(targetSchema, sourceSchema);
    await button(manage.preview).click();
    await expect(panel.getByRole('alert')).toContainText('目标 schema 已存在同名关系 "move_order_note_idx"');
    await observer.query('DROP TABLE ' + target + '.move_order_note_idx');
    await button(manage.preview).click();
    await expect(panel.getByLabel(manage.sql, { exact: true })).toHaveText('ALTER TABLE ' + original + ' SET SCHEMA ' + target + ';');
    await expect(panel.getByLabel(manage.moveIndexes, { exact: true })).toContainText('"move_order_note_idx"');
    await expect(panel.getByLabel(manage.moveConstraints, { exact: true })).toContainText('"move_order_positive"');
    await expect(panel.getByLabel(manage.moveSequences, { exact: true })).toHaveText('"move_order_id"');
    expect(await oid(original)).toBe(originalOid);
    expect(await oid(moved)).toBeNull();
    await panel.screenshot({ path: info.outputPath('PostgreSQL 移动表预览.png') });
    await button(manage.confirmMove).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.locator('[data-workspace-tab-id="pg-move-source"]')).toHaveCount(0);
    await expect(page.locator('[data-active-workspace-tab="true"] .tab-select')).toHaveText(moved);
    await expect(gridTab.getByRole('grid')).toContainText('跨 schema 保留的记录');
    await favorite(moved);
    expect(await oid(moved)).toBe(originalOid);
    expect(await oid(original)).toBeNull();
    expect(await oid(target + '.move_order_id')).toBe(sequenceOid);
    expect(await oid(target + '.move_order_note_idx')).toBe(indexOid);
    expect(await oid(source + '.unowned_move_seq')).toBe(unownedOid);
    expect(await constraints()).toEqual(beforeConstraints);
    expect((await observer.query('SELECT note FROM ' + source + '.move_order_view')).rows).toEqual([{ note: '跨 schema 保留的记录' }]);
    expect((await observer.query(`SELECT confrelid::text AS oid FROM pg_catalog.pg_constraint
      WHERE conrelid=$1::regclass AND contype='f'`, [source + '.move_order_ref'])).rows).toEqual([{ oid: originalOid }]);
    expect((await observer.query(`INSERT INTO ${moved}(note) VALUES ('继续使用原序列') RETURNING id::text`)).rows).toEqual([{ id: '8' }]);

    await open(sourceSchema, targetSchema);
    await button(manage.preview).click();
    await expect(panel.getByLabel(manage.sql, { exact: true })).toContainText('SET SCHEMA ' + source);
    await button(manage.confirmMove).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.locator('[data-active-workspace-tab="true"] .tab-select')).toHaveText(original);
    await favorite(original);
    expect(await oid(original)).toBe(originalOid);
    const native = desktop.process();
    await quitDesktop();
    expect(native.exitCode).toBe(0);
  } finally { await observer.end(); }
});

test('PostgreSQL 移表绑定目标 schema，支持原 schema 无 CREATE 权限和分区移动', async () => {
  const config = fixture(), holder = new Client(config), observer = new Client(config);
  const adminPassword = process.env.DBARK_PG_ROLES_ADMIN_PASSWORD ?? '';
  if (!/^[a-f0-9]{64}$/.test(adminPassword)) throw Error('需要隔离库管理夹具');
  const admin = new Client({ ...config, user: 'postgres', password: adminPassword });
  await Promise.all([holder.connect(), observer.connect(), admin.connect()]);
  try {
    await admin.query(`CREATE SCHEMA move_owner_source;
      GRANT USAGE, CREATE ON SCHEMA move_owner_source TO ${config.user};
      CREATE TABLE move_owner_source.source_table(id int);
      ALTER TABLE move_owner_source.source_table OWNER TO ${config.user};
      REVOKE CREATE ON SCHEMA move_owner_source FROM ${config.user}`);
    await holder.query(`CREATE SCHEMA move_owner_dest; CREATE SCHEMA move_parts;
      INSERT INTO move_owner_source.source_table VALUES (17);
      CREATE TABLE move_parts.partition_root(id int PRIMARY KEY) PARTITION BY RANGE(id);
      CREATE TABLE move_parts.partition_leaf PARTITION OF move_parts.partition_root FOR VALUES FROM (0) TO (10);
      INSERT INTO move_parts.partition_root VALUES (2);
      CREATE TABLE public.move_race(id int); INSERT INTO public.move_race VALUES (11);
      CREATE TABLE public.move_postcheck(id int); INSERT INTO public.move_postcheck VALUES (33);
      CREATE SCHEMA move_late_dest`);
    const connectionId = await saveConnection(config), database = config.database;
    const read = (table: string) => page.evaluate(input => window.dbark.invoke('postgres.structure.read', input), { connectionId, database, table });
    const prepare = async (table: string, schema: string) => {
      const facts = (await read(table)).tableManage;
      expect(facts?.move).toBe(true);
      return page.evaluate(draft => window.dbark.invoke('postgres.tableManage.preview', draft),
        { connectionId, database, table, schema, action: 'move' as const, stamp: facts!.stamp });
    };
    const apply = (token: string) => page.evaluate(input => window.dbark.invoke('postgres.tableManage.apply', input),
      { connectionId, database, token, confirmed: true as const });
    const original = '"move_owner_source"."source_table"';
    expect((await read(original)).tableManage).toMatchObject({ rename: false, move: true });
    await expect(prepare(original, 'move_owner_source')).rejects.toThrow();
    const stale = await prepare(original, 'move_owner_dest');
    await holder.query('ALTER SCHEMA move_owner_dest RENAME TO retired_move_dest; CREATE SCHEMA move_owner_dest');
    expect(await apply(stale.token)).toMatchObject({ outcome: 'notSent', message: expect.stringContaining('目标 schema') });
    expect((await observer.query('SELECT id FROM move_owner_source.source_table')).rows).toEqual([{ id: 17 }]);
    await holder.query('CREATE DOMAIN move_owner_dest.source_table AS integer');
    await expect(prepare(original, 'move_owner_dest')).rejects.toThrow('同名类型');
    await holder.query('DROP DOMAIN move_owner_dest.source_table');
    expect(await apply((await prepare(original, 'move_owner_dest')).token)).toMatchObject({ outcome: 'committed' });
    expect((await observer.query('SELECT id FROM move_owner_dest.source_table')).rows).toEqual([{ id: 17 }]);

    const root = await prepare('"move_parts"."partition_root"', 'move_owner_dest');
    expect(await apply(root.token)).toMatchObject({ outcome: 'committed' });
    expect((await observer.query(`SELECT tableoid::regclass::text AS leaf,id FROM move_owner_dest.partition_root`)).rows)
      .toEqual([{ leaf: 'move_parts.partition_leaf', id: 2 }]);
    const leaf = await prepare('"move_parts"."partition_leaf"', 'move_owner_dest');
    expect(await apply(leaf.token)).toMatchObject({ outcome: 'committed' });
    expect((await observer.query(`SELECT tableoid::regclass::text AS leaf,id FROM move_owner_dest.partition_root`)).rows)
      .toEqual([{ leaf: 'move_owner_dest.partition_leaf', id: 2 }]);

    const race = await prepare('"public"."move_race"', 'move_owner_dest');
    await holder.query('BEGIN; LOCK TABLE public.move_race IN ACCESS EXCLUSIVE MODE');
    const applying = apply(race.token);
    void applying.catch(() => undefined);
    try {
      await expect.poll(async () => (await observer.query(`SELECT EXISTS(SELECT FROM pg_catalog.pg_stat_activity
        WHERE wait_event_type='Lock' AND query LIKE $1) AS waiting`, ['SELECT 1 FROM ONLY "public"."move_race"%'])).rows[0].waiting,
      { timeout: 3500 }).toBe(true);
      await holder.query(`ALTER TABLE public.move_race RENAME TO move_race_original;
        CREATE TABLE public.move_race(id int); INSERT INTO public.move_race VALUES (22); COMMIT`);
    } finally { await holder.query('ROLLBACK'); }
    expect(await applying).toMatchObject({ outcome: 'notSent' });
    expect((await observer.query('SELECT id FROM public.move_race_original UNION ALL SELECT id FROM public.move_race')).rows)
      .toEqual([{ id: 11 }, { id: 22 }]);
    expect((await observer.query("SELECT to_regclass('move_owner_dest.move_race') AS target")).rows[0].target).toBeNull();

    const postcheck = '"public"."move_postcheck"';
    const associationPreview = await prepare(postcheck, 'move_late_dest');
    await holder.query('CREATE INDEX move_postcheck_idx ON public.move_postcheck(id)');
    expect(await apply(associationPreview.token)).toMatchObject({ outcome: 'notSent', message: expect.stringContaining('随迁对象') });

    // 在 ALTER 已发送后更换目标 schema，验证提交前的 OID 核对会回滚已执行的移动。
    await admin.query(`CREATE FUNCTION public.move_schema_gate() RETURNS event_trigger LANGUAGE plpgsql AS $$
      BEGIN
        IF current_user = '${config.user}' AND current_query() LIKE 'ALTER TABLE "public"."move_postcheck" SET SCHEMA %' THEN
          PERFORM pg_catalog.pg_advisory_xact_lock(54098327);
        END IF;
      END; $$;
      CREATE EVENT TRIGGER move_schema_gate ON ddl_command_start WHEN TAG IN ('ALTER TABLE')
      EXECUTE FUNCTION public.move_schema_gate()`);
    const late = await prepare(postcheck, 'move_late_dest');
    await holder.query('SELECT pg_advisory_lock(54098327)');
    const moving = apply(late.token);
    void moving.catch(() => undefined);
    try {
      await expect.poll(async () => (await observer.query(`SELECT EXISTS(SELECT FROM pg_catalog.pg_stat_activity
        WHERE wait_event='advisory' AND query LIKE $1) AS waiting`, ['ALTER TABLE "public"."move_postcheck" SET SCHEMA%'])).rows[0].waiting,
      { timeout: 3500 }).toBe(true);
      await holder.query('ALTER SCHEMA move_late_dest RENAME TO retired_move_late; CREATE SCHEMA move_late_dest');
    } finally { await holder.query('SELECT pg_advisory_unlock(54098327)'); }
    expect(await moving).toMatchObject({ outcome: 'rolledBack', message: expect.stringContaining('未确认原表及随迁对象') });
    expect((await observer.query('SELECT id FROM public.move_postcheck')).rows).toEqual([{ id: 33 }]);
    expect((await observer.query("SELECT to_regclass('move_late_dest.move_postcheck') AS moved")).rows[0].moved).toBeNull();
    const native = desktop.process();
    await quitDesktop();
    expect(native.exitCode).toBe(0);
  } finally { await Promise.all([holder.end(), observer.end(), admin.end()]); }
});
