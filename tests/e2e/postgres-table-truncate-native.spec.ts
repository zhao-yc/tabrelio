function isolatedConnection() {
  const user = process.env.DBARK_POSTGRES_TEST_USER ?? '', database = process.env.DBARK_POSTGRES_TEST_DATABASE ?? '';
  const password = process.env.DBARK_POSTGRES_TEST_PASSWORD ?? '', port = Number(process.env.DBARK_POSTGRES_TEST_PORT);
  if (process.env.DBARK_INTEGRATION_ENABLED !== '1' || !/^tabrelio_pg_[a-f0-9]{12}$/.test(user) || database !== user ||
      !/^[a-f0-9]{64}$/.test(password) || !Number.isInteger(port) || port <= 1024 || port > 65535) throw Error('需要本轮独占回环库');
  return { host: '127.0.0.1', port, user, database, password, connectionTimeoutMillis: 3000 };
}

async function saveConnection(connection: ReturnType<typeof isolatedConnection>) {
  return page.evaluate(async ({ host, port, user, database, password }) => (await window.dbark.invoke('connections.save', {
    id: '', name: 'PostgreSQL 清空数据 ' + user, group: '', color: '#123456', dialect: 'postgresql',
    host, port, user, database, password, rememberPassword: false,
  })).id, connection);
}

test('PostgreSQL 清空表保留标签，按所选策略处理序列和外键', async ({}, info) => {
  const config = isolatedConnection(), observer = new Client(config);
  const target = '"public"."清空 目标"', sequence = '"public"."clear_identity"';
  await observer.connect();
  try {
    await observer.query(`CREATE TABLE ${target}(id bigint GENERATED BY DEFAULT AS IDENTITY
      (SEQUENCE NAME public.clear_identity START WITH 8) PRIMARY KEY, note text);
      CREATE TABLE public.clear_audit(event text);
      CREATE FUNCTION public.log_clear() RETURNS trigger LANGUAGE plpgsql AS
        $$ BEGIN INSERT INTO public.clear_audit VALUES (TG_OP); RETURN NULL; END; $$;
      CREATE TRIGGER clear_audit AFTER TRUNCATE ON ${target} FOR EACH STATEMENT EXECUTE FUNCTION public.log_clear();
      CREATE TRIGGER delete_audit AFTER DELETE ON ${target} FOR EACH STATEMENT EXECUTE FUNCTION public.log_clear();
      INSERT INTO ${target}(note) VALUES ('原记录甲'),('原记录乙');`);
    const values = async () => (await observer.query('SELECT id::text,note FROM ' + target + ' ORDER BY id')).rows;
    const seq = async () => (await observer.query('SELECT last_value::text,is_called FROM ' + sequence)).rows[0];
    const events = async () => (await observer.query('SELECT event FROM public.clear_audit')).rows.map(row => row.event);
    const relation = async () => (await observer.query('SELECT to_regclass($1)::oid::text AS oid', [target])).rows[0].oid;
    const oid = await relation();
    const connectionId = await saveConnection(config);
    await page.evaluate(async ({ connectionId, database, target }) => {
      const settings = await window.dbark.invoke('settings.get', {});
      await window.dbark.invoke('settings.save', { ...settings, activeTabId: 'pg-truncate-target', tabs: [
        { id: 'pg-truncate-target', title: '清空测试表页', kind: 'table', connectionId, database, table: target },
      ] });
    }, { connectionId, database: config.database, target });
    await page.reload();
    const tab = page.locator('.postgres-table-tab:visible'), dialog = page.getByRole('dialog', { name: structure.title, exact: true });
    const section = dialog.getByRole('region', { name: manage.title, exact: true });
    const action = (name: string) => section.getByRole('button', { name, exact: true });
    const open = async (identity: 'continue' | 'restart') => {
      await tab.getByRole('button', { name: structure.open, exact: true }).click();
      await dialog.getByRole('button', { name: manage.title, exact: true }).click();
      await section.getByRole('combobox', { name: manage.operation, exact: true }).selectOption('truncate');
      const strategy = section.getByRole('combobox', { name: manage.identity, exact: true });
      await expect(strategy).toHaveValue('continue');
      await strategy.selectOption(identity);
      await action(manage.preview).click();
      const sql = section.getByLabel(manage.sql, { exact: true });
      await expect(sql).toHaveText('LOCK TABLE ONLY ' + target + ' IN ACCESS EXCLUSIVE MODE; TRUNCATE TABLE ONLY ' +
        target + (identity === 'restart' ? ' RESTART IDENTITY' : ' CONTINUE IDENTITY') + ' RESTRICT;');
      await expect(section.getByLabel(manage.affectedTables, { exact: true })).toHaveText(target);
      await expect(action(manage.confirmTruncate)).toBeDisabled();
      const confirmation = section.getByLabel(manage.acknowledgeTruncate, { exact: true });
      await confirmation.fill('另一张表');
      await expect(action(manage.confirmTruncate)).toBeDisabled();
      await confirmation.fill('清空 目标');
    };
    await expect(tab.getByRole('grid')).toContainText('原记录甲');
    await open('continue');
    expect(await values()).toHaveLength(2);
    expect(await seq()).toEqual({ last_value: '9', is_called: true });
    expect(await events()).toEqual([]);
    await section.screenshot({ path: info.outputPath('PostgreSQL 清空数据预览.png') });
    await action(manage.confirmTruncate).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.locator('[data-workspace-tab-id="pg-truncate-target"][data-active-workspace-tab="true"]')).toBeVisible();
    await expect(tab.getByText(table.page(0, 0), { exact: true })).toBeVisible();
    expect(await values()).toEqual([]);
    expect(await seq()).toEqual({ last_value: '9', is_called: true });
    expect(await relation()).toBe(oid);
    expect(await events()).toEqual(['TRUNCATE']);

    const inserted = await observer.query('INSERT INTO ' + target + "(note) VALUES ('外键保护') RETURNING id::text");
    expect(inserted.rows[0].id).toBe('10');
    await observer.query('CREATE TABLE public.clear_reference(id bigint REFERENCES ' + target + '(id)); INSERT INTO public.clear_reference VALUES (10)');
    await open('restart');
    await expect(section.getByLabel(manage.affectedSequences, { exact: true })).toHaveText(sequence);
    await section.screenshot({ path: info.outputPath('PostgreSQL 清空数据并重置序列预览.png') });
    await action(manage.confirmTruncate).click();
    await expect(section.getByRole('alert')).toContainText(/foreign key|外键/);
    expect(await values()).toEqual([{ id: '10', note: '外键保护' }]);
    expect(await seq()).toEqual({ last_value: '10', is_called: true });
    expect(await events()).toEqual(['TRUNCATE']);
    await action(manage.close).click();
    await dialog.getByRole('button', { name: structure.close, exact: true }).click();
    await observer.query('DROP TABLE public.clear_reference');

    await open('restart');
    await action(manage.confirmTruncate).click();
    await expect(dialog).toHaveCount(0);
    expect(await values()).toEqual([]);
    expect(await seq()).toEqual({ last_value: '8', is_called: false });
    expect(await events()).toEqual(['TRUNCATE', 'TRUNCATE']);
    expect(await relation()).toBe(oid);
    const native = desktop.process();
    await quitDesktop();
    expect(native.exitCode).toBe(0);
  } finally { await observer.end(); }
});

test('PostgreSQL 清空核对整棵分区树、授权范围和等锁同名替换', async () => {
  const config = isolatedConnection(), holder = new Client(config), observer = new Client(config);
  const limited = config.user + '_limited';
  await Promise.all([holder.connect(), observer.connect()]);
  try {
    await holder.query(`CREATE SCHEMA clear_parts;
      CREATE TABLE public.clear_root(bucket int,id bigint GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME public.clear_root_id START WITH 20)) PARTITION BY RANGE(bucket);
      CREATE TABLE public.clear_left PARTITION OF public.clear_root FOR VALUES FROM (0) TO (10);
      CREATE TABLE clear_parts.clear_right PARTITION OF public.clear_root FOR VALUES FROM (10) TO (20);
      INSERT INTO public.clear_root(bucket) VALUES (1),(11);
      CREATE TABLE public.clear_parent(id int);
      CREATE TABLE public.clear_inherited() INHERITS (public.clear_parent);
      INSERT INTO public.clear_parent VALUES (1); INSERT INTO public.clear_inherited VALUES (2);
      CREATE UNLOGGED TABLE public.clear_race(id integer); INSERT INTO public.clear_race VALUES(11);
      CREATE TABLE public.clear_delegated(id bigserial); INSERT INTO public.clear_delegated DEFAULT VALUES;
      GRANT TRUNCATE ON public.clear_delegated TO ${limited}`);
    const owner = await saveConnection(config), delegate = await saveConnection({ ...config, user: limited });
    const input = (table: string, connectionId = owner) => ({ table, connectionId, database: config.database });
    const read = (target: ReturnType<typeof input>) => page.evaluate(target => window.dbark.invoke('postgres.structure.read', target), target);
    const prepare = async (target: ReturnType<typeof input>, identity: 'continue' | 'restart' = 'continue') => {
      const capability = (await read(target)).tableManage;
      expect(capability?.truncate).toBe(true);
      return page.evaluate(request => window.dbark.invoke('postgres.tableManage.preview', request),
        { ...target, stamp: capability!.stamp, action: 'truncate' as const, identity });
    };
    const apply = ({ connectionId, database }: ReturnType<typeof input>, token: string) => page.evaluate(
      request => window.dbark.invoke('postgres.tableManage.apply', { ...request, confirmed: true }), { connectionId, database, token });
    const count = async (table: string) => (await observer.query('SELECT count(*)::int AS n FROM ' + table)).rows[0].n;
    const root = input('"public"."clear_root"'), leaf = input('"public"."clear_left"');
    const leafPlan = await prepare(leaf);
    expect(leafPlan.truncateScope).toEqual({ tables: [leaf.table], sequences: [] });
    expect(await apply(leaf, leafPlan.token)).toMatchObject({ outcome: 'committed' });
    expect(await count('clear_parts.clear_right')).toBe(1);
    expect(await count('public.clear_left')).toBe(0);
    const rootPlan = await prepare(root, 'restart');
    expect(rootPlan.truncateScope).toEqual({ tables: [root.table, leaf.table, '"clear_parts"."clear_right"'], sequences: ['"public"."clear_root_id"'] });
    await holder.query(`CREATE TABLE clear_parts.clear_new PARTITION OF public.clear_root FOR VALUES FROM (20) TO (30);
      INSERT INTO public.clear_root(bucket) VALUES (21)`);
    expect(await apply(root, rootPlan.token)).toMatchObject({ outcome: 'notSent', message: expect.stringContaining('范围') });
    expect(await count('public.clear_root')).toBe(2);
    const renewed = await prepare(root, 'restart');
    expect(renewed.truncateScope?.tables).toContain('"clear_parts"."clear_new"');
    expect(await apply(root, renewed.token)).toMatchObject({ outcome: 'committed' });
    expect(await count('public.clear_root')).toBe(0);
    expect((await observer.query('INSERT INTO public.clear_root(bucket) VALUES (1) RETURNING id::text')).rows[0].id).toBe('20');

    const inherited = input('"public"."clear_parent"');
    expect(await apply(inherited, (await prepare(inherited)).token)).toMatchObject({ outcome: 'committed' });
    expect(await count('ONLY public.clear_parent')).toBe(0);
    expect(await count('public.clear_inherited')).toBe(1);

    const delegated = input('"public"."clear_delegated"', delegate);
    expect((await read(delegated)).tableManage).toMatchObject({ rename: false, drop: false, truncate: true });
    await expect(prepare(delegated, 'restart')).rejects.toThrow();
    expect(await apply(delegated, (await prepare(delegated)).token)).toMatchObject({ outcome: 'committed' });
    expect(await count('public.clear_delegated')).toBe(0);

    const race = input('"public"."clear_race"'), racePlan = await prepare(race);
    await holder.query('BEGIN; LOCK TABLE public.clear_race IN ACCESS EXCLUSIVE MODE');
    const applying = apply(race, racePlan.token);
    void applying.catch(() => undefined);
    try {
      await expect.poll(async () => (await observer.query(`SELECT EXISTS(SELECT FROM pg_catalog.pg_stat_activity
        WHERE wait_event_type='Lock' AND query LIKE $1) AS waiting`, ['LOCK TABLE ONLY "public"."clear_race"%'])).rows[0].waiting,
      { timeout: 3500 }).toBe(true);
      await holder.query(`ALTER TABLE public.clear_race RENAME TO clear_race_original;
        CREATE UNLOGGED TABLE public.clear_race(id integer); INSERT INTO public.clear_race VALUES (22); COMMIT`);
    } finally { await holder.query('ROLLBACK'); }
    expect(await applying).toMatchObject({ outcome: 'notSent' });
    await expect(apply(race, racePlan.token)).rejects.toThrow();
    expect((await observer.query('SELECT id FROM public.clear_race_original UNION ALL SELECT id FROM public.clear_race')).rows)
      .toEqual([{ id: 11 }, { id: 22 }]);
    const native = desktop.process();
    await quitDesktop();
    expect(native.exitCode).toBe(0);
  } finally { await Promise.all([holder.end(), observer.end()]); }
});
